#!/usr/bin/env python3
"""Direction-quantiser decision logic -> Espresso -> verified cover -> rtl/dir_decide.sv.

The two Sobel comparators (c0: 32|Gy| <= 13|Gx|, c2: 32|Gx| <= 13|Gy|) are arithmetic and stay in
rtl/sobel.sv.  What follows them is a 4-input Boolean function that picks the gradient sector, which is
also the NMS neighbour-pair select:

    inputs  c0 c2 sx sy                      (sx, sy = sign bits of Gx, Gy)
    outputs dir[1:0]  00 W/E, 01 NW/SE (signs equal), 10 N/S, 11 NE/SW (signs differ)
    priority c0 -> 00, else c2 -> 10, else sx==sy -> 01, else 11
    don't-care: c0=c2=1 with sx|sy (c0&c2 only when |Gx|=|Gy|=0, whose sign bits are 0)

Espresso: PyEDA's binding of the UC Berkeley Espresso engine.  Everything printed is measured here;
the cover is checked against the specification on every care input before RTL is written.
"""
import itertools, json, sys
from pathlib import Path
from pyeda.inter import exprvars, truthtable
from pyeda.boolalg.minimization import espresso_tts

ROOT = Path(__file__).resolve().parents[1]
NAMES = ("c0", "c2", "sx", "sy")

def spec(c0, c2, sx, sy):
    """Return (dir1, dir0) or None for don't-care."""
    if c0 and c2 and (sx or sy):
        return None
    if c0: return (0, 0)
    if c2: return (1, 0)
    return (0, 1) if sx == sy else (1, 1)

X = exprvars("x", 4)          # x[0]=c0, x[1]=c2, x[2]=sx, x[3]=sy
# PyEDA truth-table row k has x[0] as the least-significant bit of k.
def row_inputs(k):
    return tuple((k >> i) & 1 for i in range(4))

def build(bit, use_dc=True):
    s = ""
    for k in range(16):
        v = spec(*row_inputs(k))
        s += ("-" if v is None and use_dc else ("0" if v is None else str(v[bit])))
    return s.replace("-", "X")

def cover_for(bit, use_dc=True):
    tt = truthtable(X, build(bit, use_dc))
    (e,) = espresso_tts(tt)
    return e

def terms_of(expr):
    """Return list of product terms, each a dict name->polarity."""
    out = []
    dnf = expr.to_dnf()
    cl = dnf.xs if hasattr(dnf, "xs") else (dnf,)
    if dnf.is_zero(): return []
    if dnf.is_one(): return [{}]
    # a single literal / product is not wrapped in an OrOp
    from pyeda.boolalg.expr import OrOp
    prods = dnf.xs if isinstance(dnf, OrOp) else (dnf,)
    for p in prods:
        lits = {}
        items = p.xs if hasattr(p, "xs") and not hasattr(p, "indices") else (p,)
        for l in items:
            idx = l.inputs[0].indices[0] if hasattr(l, "inputs") else l.indices[0]
            neg = str(l).startswith("~")
            lits[NAMES[idx]] = 0 if neg else 1
        out.append(lits)
    return out

def eval_cover(terms, c0, c2, sx, sy):
    v = dict(c0=c0, c2=c2, sx=sx, sy=sy)
    return int(any(all(v[n] == p for n, p in t.items()) for t in terms))

def main():
    covers = {b: terms_of(cover_for(b)) for b in (0, 1)}   # key = index into spec tuple (dir1, dir0)
    nodc = {b: terms_of(cover_for(b, use_dc=False)) for b in (0, 1)}
    # exhaustive check over the 12 care rows (and report don't-care behaviour)
    ok = True
    for k in range(16):
        r = row_inputs(k)
        s = spec(*r)
        if s is None: continue
        got = (eval_cover(covers[0], *r), eval_cover(covers[1], *r))
        if got != s:
            ok = False; print("MISMATCH", r, got, s)
    def cube(t): return " & ".join((n if p else "~" + n) for n, p in sorted(t.items(), key=lambda kv: NAMES.index(kv[0]))) or "1'b1"
    # BEFORE: canonical minterm SOP over care rows (every ON minterm is a 4-literal product)
    before = {b: sum(1 for k in range(16) if spec(*row_inputs(k)) and spec(*row_inputs(k))[b] == 1) for b in (0, 1)}
    eq = {b: " | ".join("(" + cube(t) + ")" for t in covers[b]) or "1'b0" for b in (0, 1)}
    nterms = sum(len(covers[b]) for b in covers)
    nlits = sum(len(t) for b in covers for t in covers[b])
    n0terms = sum(len(nodc[b]) for b in nodc)
    n0lits = sum(len(t) for b in nodc for t in nodc[b])
    bt = sum(before.values()); bl = 4 * bt
    print(f"dir[1] = {eq[0]}\ndir[0] = {eq[1]}")
    print(f"BEFORE canonical minterms: {bt} terms / {bl} literals;  AFTER Espresso (with don't-cares): {nterms} terms / {nlits} literals;"
          f"  WITHOUT don't-cares: {n0terms} / {n0lits};  cover == spec on all care rows: {ok}")
    if not ok: sys.exit(1)
    # one-hot view (NMS pair select) for the report
    rtl = f"""`default_nettype none
// GENERATED by logic/espresso_direction.py - do not edit by hand.
// Espresso-minimised sector decision.  c0/c2 are the Sobel direction comparators, sx/sy the gradient sign bits.
// dir: 00 = W/E, 01 = NW/SE (signs equal), 10 = N/S, 11 = NE/SW (signs differ).
// c0&c2 with a sign bit set cannot occur (both comparators hold only when Gx = Gy = 0); those rows were
// don't-cares for the minimiser.
module dir_decide (
  input  wire c0, c2, sx, sy,
  output wire [1:0] dir
);
  assign dir[1] = {eq[0]};
  assign dir[0] = {eq[1]};
endmodule
`default_nettype wire
"""
    (ROOT / "rtl" / "dir_decide.sv").write_text(rtl)
    rep = dict(before_terms=bt, before_literals=bl, after_terms=nterms, after_literals=nlits,
               nodc_terms=n0terms, nodc_literals=n0lits, dir1=eq[0], dir0=eq[1], verified_on_care_rows=ok,
               tool="pyeda %s Espresso binding" % __import__("pyeda").__version__)
    (ROOT / "logic" / "espresso_report.json").write_text(json.dumps(rep, indent=2) + "\n")

if __name__ == "__main__":
    main()
