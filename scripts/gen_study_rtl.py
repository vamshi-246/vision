#!/usr/bin/env python3
"""Generate rtl/study/paper_system.sv from rtl/top.sv: the identical Gaussian/Sobel/NMS front end with classify_hist replaced by the
paper's frame-buffer + histogram + Otsu engine (rtl/study/paper).  Synthesis-comparison artifact only (not simulated as a system;
the paper engine itself is simulated by scripts/paper_quality.py)."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
top = (ROOT / "rtl/top.sv").read_text()
a = top.index("  localparam int unsigned G_W")
b = top.index("  assign nms_eof")
b = top.index("\n", b) + 1
body = top[a:b]
hdr = '''`default_nettype none
// GENERATED by scripts/gen_study_rtl.py from rtl/top.sv - do not edit.
// PAPER variant for the resource comparison: identical front end (Gaussian, Sobel, direction/NMS), then the paper's adaptive
// engine (whole-frame buffer, histogram, log-domain Otsu, classifier) instead of the streaming classifier.
module paper_system #(
  parameter int unsigned IMG_W = 640, parameter int unsigned IMG_H = 480,
  parameter int unsigned X_W = $clog2(IMG_W), parameter int unsigned Y_W = $clog2(IMG_H)
) (
  input  wire clk, rst, in_valid, in_sof, in_eol, input wire [7:0] in_gray, input wire start,
  output wire done, output wire [7:0] t_hi, t_lo, output wire class_valid, output wire [1:0] class_out, output wire [31:0] edge_count
);
'''
tail = '''
  paper_top #(.W(S_W), .H(S_H), .IN_W(11)) u_paper (
    .clk, .rst, .start, .busy(), .done, .pix_ready(), .pix_valid(n_win_valid), .pix_data(nms_mag),
    .t_hi, .t_lo, .class_valid, .class_out, .edge_count
  );
endmodule
`default_nettype wire
'''
# the front end declares cls_valid/cls for the streaming classifier; keep them unused
(ROOT / "rtl/study/paper_system.sv").write_text(hdr + body + tail)
base = '''`default_nettype none
// BASELINE for the comparison: plain Sobel (|Gx|+|Gy|) on the unsmoothed gray stream with ONE global threshold: no Gaussian, no
// direction-based NMS, no double threshold.  Uses the same line buffer and the same hand-HLS Sobel as the main design.
module baseline_top #(
  parameter int unsigned IMG_W = 640, parameter int unsigned IMG_H = 480, parameter int unsigned THR = 192,
  parameter int unsigned X_W = $clog2(IMG_W), parameter int unsigned Y_W = $clog2(IMG_H)
) (
  input wire clk, rst, in_valid, in_sof, in_eol, input wire [7:0] in_gray,
  output logic out_valid, output logic edge_o
);
  logic wv; logic [X_W-1:0] wx; logic [Y_W-1:0] wy;
  logic [7:0] w00,w01,w02,w10,w11,w12,w20,w21,w22;
  linebuf #(.IMG_W(IMG_W), .IMG_H(IMG_H), .DATA_W(8), .X_W(X_W), .Y_W(Y_W)) lb (
    .clk, .rst, .pix_valid(in_valid), .pix_sof(in_sof), .pix_eol(in_eol), .pix_data(in_gray),
    .win_valid(wv), .win_x(wx), .win_y(wy), .w00, .w01, .w02, .w10, .w11, .w12, .w20, .w21, .w22);
  logic sv; logic [10:0] mag;
  sobel sb(.clk, .in_valid(wv), .w00, .w01, .w02, .w10, .w11, .w12, .w20, .w21, .w22, .out_valid(sv), .magnitude(mag), .direction());
  always_ff @(posedge clk) begin out_valid <= sv; edge_o <= sv && (mag >= 11'(THR)); end
endmodule
`default_nettype wire
'''
(ROOT / "rtl/study/baseline_top.sv").write_text(base)
print("generated rtl/study/paper_system.sv and rtl/study/baseline_top.sv")
