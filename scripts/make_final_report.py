"""Generate docs/FINAL_REPORT.md. Every number comes from a measured artifact (JSON/report/log) - none is typed here."""
import hashlib, json, re
from pathlib import Path
import numpy as np
ROOT = Path(__file__).resolve().parents[1]
B = ROOT / "build"

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def timing(rpt):
    t = Path(rpt).read_text()
    m = re.search(r"WNS\(ns\).*?\n\s*-+.*?\n\s*(-?[\d.]+)\s+(-?[\d.]+)\s+(\d+)\s+(\d+)\s+(-?[\d.]+)\s+(-?[\d.]+)\s+(\d+)\s+(\d+)", t, re.S)
    return dict(wns=m.group(1), tns_fail=m.group(3), whs=m.group(5), hold_fail=m.group(7), endpoints=m.group(4))
def util(rpt):
    t = Path(rpt).read_text()
    g = lambda p: re.search(p, t).group(1)
    return dict(lut=g(r"\| Slice LUTs\*?\s+\|\s+(\d+)"), ff=g(r"\| Slice Registers\s+\|\s+(\d+)"), ramb36=g(r"\|\s*RAMB36/FIFO\*\s+\|\s+(\d+)"),
                ramb18=g(r"\|\s*RAMB18\s+\|\s+(\d+)"), dsp=g(r"\|\s*DSPs\s+\|\s+(\d+)"))

ooc = json.loads((B / "ooc/results.json").read_text())
ctl = json.loads((B / "formal/ctl_results.json").read_text())
espr = json.loads((ROOT / "logic/espresso_report.json").read_text())
qd = json.loads((B / "paper/quality_detail.json").read_text())
otsu = json.loads((B / "paper/otsu_check.json").read_text())
core = json.loads((B / "core_regression/summary.json").read_text())
vid = json.loads((B / "video_regression/summary.json").read_text())
tz, tz7 = timing(B / "hdmi/timing.rpt"), timing(B / "hdmi_z7/timing.rpt")
uz, uz7 = util(B / "hdmi/utilization.rpt"), util(B / "hdmi_z7/utilization.rpt")
bit, bit7 = sha(B / "hdmi/zybo_edge_hdmi.bit"), sha(B / "hdmi_z7/zybo_edge_hdmi.bit")
fsum = json.loads((B / "hdmi_sim_functional/summary.json").read_text())
fsum7 = json.loads((B / "hdmi_sim_functional_hdmi_z7/summary.json").read_text())

def q(ref, key, f): return np.mean([qd[i][ref][key][f] for i in qd])
core640 = [r for r in core if r["width"] == 640]
c640frames = core640[0]["frames"]; c640cmp = sum(int(re.search(r"out=(\d+)", r["result"]).group(1)) for r in core640)
n_vid = len(vid); n_vid_img = sum(1 for r in vid if r.get("img"))
pix_clk = 25.178571   # MHz, from the generated Clocking Wizard solution (M=35.25, D=5, O=35/7); see build/hdmi/clocks.rpt
delay = 3 * 800 + 15   # measured: tb/video/tb_latency.sv gives 687 clocks at HT=224 = 3*HT+15
lat_clk = delay + 2
res_rows = "\n".join(
    f"| {k} | {v['lut']:.0f} | {v['ff']:.0f} | {v['ramb36']:.0f} / {v['ramb18']:.0f} ({v['bram_tiles']:g} tiles) | {v['dsp']:.0f} | "
    + (f"{v['wns']:+.2f} ns (fmax about {1000/(v['period']-v['wns']):.0f} MHz)" if v.get("wns") is not None else "synthesis only") + " |"
    for k, v in ooc.items())
def ctl_rows(name):
    d = ctl[name]
    return "\n".join(f"| {k} | {'TRUE' if v else 'FALSE'} |" for k, v in d["properties"].items()) + \
        f"\n| transition relation total (no deadlock state) | {'TRUE' if d['deadlock_free'] else 'FALSE'} |"
def mut_rows(name):
    return "\n".join(f"| {m} | {', '.join(c.split()[0] for c in caught)} |" for m, caught in ctl[name]["mutants"].items())
qrows = []
for ref, label in (("vs_canny", "scikit-image Canny (external reference)"), ("vs_golden", "project golden model, thresholds 64/192, strong+weak")):
    qrows.append(f"\n**Reference: {label}** (mean over {len(qd)} images)\n\n| design / map | PSNR dB | F1 | F1 (1 px tolerance) | edge px |\n|---|---|---|---|---|")
    names = {"ours_strong_192": "OURS strong (192)", "ours_strong_weak_64_192": "OURS strong+weak (64/192)", "paper_strong": "PAPER strong (adaptive Otsu T_hi)",
             "paper_strong_weak": "PAPER strong+weak (>= T_lo)", "baseline_sobel_192": "BASELINE plain Sobel >= 192"}
    for k, n in names.items():
        psnr = q(ref, k, "psnr")
        qrows.append(f"| {n} | {'inf (identical to reference)' if np.isinf(psnr) else f'{psnr:.2f}'} | {q(ref,k,'f1'):.3f} | {q(ref,k,'f1_tol1'):.3f} | {q(ref,k,'edges'):.0f} |")
otsu_rows = "\n".join(f"| {i} | {v['rtl_t_hi']} | {v['exact_k']} | {v['abs_diff']} |" for i, v in otsu.items())
paper_rows = "\n".join(f"| {i} | {d['paper_line'].split(' ',2)[2]} |" for i, d in qd.items())

